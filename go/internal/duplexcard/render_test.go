type goldenFile struct {
	Reference string       `json:"reference"`
	Fields    []string     `json:"fields"`
	Cases     []goldenCase `json:"cases"`
}

type goldenCase struct {
	Language string         `json:"language"`
	Case     string         `json:"case"`
	Card     map[string]any `json:"card"`
	Text     string         `json:"text"`
}

func loadGoldens(t *testing.T) goldenFile {
	t.Helper()
	b, err := os.ReadFile("testdata/golden_cards.json")
	if err != nil {
		t.Fatalf("read goldens: %v", err)
	}
	var g goldenFile
	if err := json.Unmarshal(b, &g); err != nil {
		t.Fatalf("parse goldens: %v", err)
	}
	return g
}

// The goldens were generated by the reference with the template selected
// separately from the card, so most cases' cards do not carry "language".
// Render selects the template from the card, so put the case's language in.
func TestRenderMatchesReferenceGoldens(t *testing.T) {
	g := loadGoldens(t)
	if len(g.Cases) != 72 {
		t.Fatalf("golden file has %d cases, want 72", len(g.Cases))
	}
	if len(g.Fields) != len(cardFields) {
		t.Fatalf("golden fields = %v, want %v", g.Fields, cardFields)
	}
	for i, f := range cardFields {
		if g.Fields[i] != f {
			t.Fatalf("golden field %d = %q, want %q", i, g.Fields[i], f)
		}
	}

	ran := 0
	for _, tc := range g.Cases {
		tc := tc
		t.Run(tc.Language+"/"+tc.Case, func(t *testing.T) {
			tc.Card["language"] = tc.Language
			got, err := Render(tc.Card)
			if err != nil {
				t.Fatalf("Render: %v", err)
			}
			if got != tc.Text {
				t.Fatalf("text differs\n got: %q\nwant: %q", got, tc.Text)
			}
			ran++
		})
	}
	if ran != 72 {
		t.Fatalf("ran %d golden cases, want 72", ran)
	}
}

func TestRenderDefaultsToEnglish(t *testing.T) {
	got, err := Render(nil)
	if err != nil {
		t.Fatalf("Render(nil): %v", err)
	}
	want := "You are the person described below, talking with the other person by voice."
	if got != want {
		t.Fatalf("got %q, want %q", got, want)
	}

	for _, lang := range []string{"", "   "} {
		got, err := Render(map[string]any{"language": lang})
		if err != nil {
			t.Fatalf("Render(language=%q): %v", lang, err)
		}
		if got != want {
			t.Fatalf("language %q got %q, want the English lead", lang, got)
		}
	}
}

func TestRenderTrimsLanguage(t *testing.T) {
	got, err := Render(map[string]any{"language": " ja ", "name": "Haru"})
	if err != nil {
		t.Fatalf("Render: %v", err)
	}
	if !strings.HasPrefix(got, "あなたは以下の人物として") {
		t.Fatalf("got %q, want the Japanese lead", got)
	}
}

func TestRenderRejectsUnsupportedLanguage(t *testing.T) {
	_, err := Render(map[string]any{"language": "xx"})
	if !errors.Is(err, ErrUnsupportedLanguage) {
		t.Fatalf("err = %v, want ErrUnsupportedLanguage", err)
	}
	if !strings.Contains(err.Error(), `"xx"`) {
		t.Fatalf("err = %q, want the language named", err)
	}
}

func TestRenderRejectsNonStringLanguage(t *testing.T) {
	_, err := Render(map[string]any{"language": float64(1)})
	if !errors.Is(err, ErrFieldType) {
		t.Fatalf("err = %v, want ErrFieldType", err)
	}
	if !strings.Contains(err.Error(), "language") {
		t.Fatalf("err = %q, want language named", err)
	}
}

func TestRenderRejectsNonStringFields(t *testing.T) {
	for _, value := range []any{float64(3), true, []any{"x"}, map[string]any{"k": "v"}} {
		_, err := Render(map[string]any{"persona": value})
		if !errors.Is(err, ErrFieldType) {
			t.Fatalf("%T: err = %v, want ErrFieldType", value, err)
		}
		if !strings.Contains(err.Error(), "persona") {
			t.Fatalf("%T: err = %q, want persona named", value, err)
		}
	}
}

func TestRenderAcceptsNilFields(t *testing.T) {
	got, err := Render(map[string]any{
		"persona": nil, "name": nil, "gender": nil, "backchannel": nil,
		"other_name": nil, "relationship": nil, "situation": nil,
	})
	if err != nil {
		t.Fatalf("Render: %v", err)
	}
	if got != "You are the person described below, talking with the other person by voice." {
		t.Fatalf("got %q, want only the lead", got)
	}
}

func TestRenderRejectsInvalidUTF8(t *testing.T) {
	_, err := Render(map[string]any{"persona": string([]byte{0xff, 0xfe})})
	if !errors.Is(err, ErrInvalidUTF8) {
		t.Fatalf("err = %v, want ErrInvalidUTF8", err)
	}
	if !strings.Contains(err.Error(), "persona") {
		t.Fatalf("err = %q, want persona named", err)
	}
}

func TestRenderRejectsControlCharacters(t *testing.T) {
	for _, r := range []rune{0x00, '\r', '\v', '\f', 0x1b, 0x7f, 0x85} {
		value := fmt.Sprintf("a%cb", r)
		_, err := Render(map[string]any{"persona": value})
		if !errors.Is(err, ErrControlCharacter) {
			t.Fatalf("%U: err = %v, want ErrControlCharacter", r, err)
		}
		if !strings.Contains(err.Error(), "persona") {
			t.Fatalf("%U: err = %q, want persona named", r, err)
		}
	}
}

func TestRenderAllowsNewlineAndTab(t *testing.T) {
	value := "line one\nline two\ttabbed"
	got, err := Render(map[string]any{"persona": value})
	if err != nil {
		t.Fatalf("Render: %v", err)
	}
	if !strings.HasSuffix(got, "[Your Persona]\n"+value) {
		t.Fatalf("got %q, want the value with its newline and tab", got)
	}
}

func TestRenderFieldAtTheByteLimit(t *testing.T) {
	value := strings.Repeat("a", MaxFieldBytes)
	got, err := Render(map[string]any{"persona": value})
	if err != nil {
		t.Fatalf("Render at the limit: %v", err)
	}
	if !strings.HasSuffix(got, value) {
		t.Fatalf("the field at the limit was not rendered")
	}
}

func TestRenderFieldOneByteOverTheLimit(t *testing.T) {
	_, err := Render(map[string]any{"persona": strings.Repeat("a", MaxFieldBytes+1)})
	if !errors.Is(err, ErrFieldTooLong) {
		t.Fatalf("err = %v, want ErrFieldTooLong", err)
	}
	if !strings.Contains(err.Error(), "persona") || !strings.Contains(err.Error(), "2000") {
		t.Fatalf("err = %q, want persona and the limit", err)
	}
}

func TestRenderJapaneseCardAtTheByteLimit(t *testing.T) {
	// Three bytes per character; the ASCII suffix makes exactly 2,000 bytes.
	value := strings.Repeat("あ", 666) + "xx"
	if len(value) != MaxFieldBytes {
		t.Fatalf("test value is %d bytes, want %d", len(value), MaxFieldBytes)
	}
	got, err := Render(map[string]any{"language": "ja", "persona": value})
	if err != nil {
		t.Fatalf("Render at the limit: %v", err)
	}
	if !strings.HasSuffix(got, value) {
		t.Fatalf("the Japanese field at the limit was not rendered")
	}
}

func TestRenderJapaneseCardOneByteOverTheLimit(t *testing.T) {
	value := strings.Repeat("あ", 667) // 2,001 bytes
	if len(value) != MaxFieldBytes+1 {
		t.Fatalf("test value is %d bytes, want %d", len(value), MaxFieldBytes+1)
	}
	_, err := Render(map[string]any{"language": "ja", "persona": value})
	if !errors.Is(err, ErrFieldTooLong) {
		t.Fatalf("err = %v, want ErrFieldTooLong", err)
	}
}

